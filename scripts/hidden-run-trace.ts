/**
 * The transparency output of the hidden run, next to the deliveries: each
 * factory run's report (time and cost per task, models, interventions) and
 * its full trace are copied to `hidden/factory-trace/<name>/`, and
 * `hidden/REPORT.md` holds the table of the whole run with links to them,
 * so the owner and the judges find them in the pushed commit. A run killed
 * before it wrote its report gets one rebuilt from its trace first. A spec
 * whose run id never appeared is listed without links. Invariant: nothing
 * here fails the hidden run; a missing file is named in REPORT.md instead.
 */

import { cpSync, existsSync, mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { runCommand } from '../src/adapters/check-runner/process';

/** The directory under `hidden/` that holds the copied reports and traces. */
export const TRACE_DIR = 'factory-trace';

/** The bound of rebuilding one report from its trace, in milliseconds. */
const REBUILD_TIMEOUT_MS = 30_000;

/** A run id as the factory makes them: one safe directory name, never a path. */
const RUN_ID = /^[a-z0-9][a-z0-9-]*$/i;

/**
 * The run id `factory run` prints first in its stdout; null when it printed
 * none or the first one is not a safe directory name. Only the first line
 * counts, so a later line an error message happens to contain is ignored.
 */
export function runIdOf(output: string): string | null {
  const id = /^run id: (\S+)$/m.exec(output)?.[1];
  return id !== undefined && RUN_ID.test(id) ? id : null;
}

/** One spec of the hidden run and the factory run that served it. */
export interface TraceEntry {
  readonly name: string;
  readonly runId: string | null;
}

/** Where the publication reads and writes, and how it rebuilds a missing report. */
export interface TraceOptions {
  readonly repoRoot: string;
  readonly hiddenDir: string;
  readonly factoryCommand: readonly string[];
  readonly env: Readonly<Record<string, string>>;
  /** The latest instant a report rebuild may run until (the hidden run's report time), epoch milliseconds. */
  readonly deadlineMs: number;
}

/** What was copied for one spec, for its line in REPORT.md. */
interface Published {
  readonly entry: TraceEntry;
  readonly files: readonly string[];
}

/** Rebuilds `runs/<runId>/report.md` from the trace with `factory report`; a failure leaves it missing. */
async function rebuildReport(options: TraceOptions, runId: string): Promise<void> {
  const [command, ...args] = [...options.factoryCommand, 'report', runId];
  await runCommand({
    command: command ?? '',
    args,
    cwd: options.repoRoot,
    timeoutMs: Math.max(0, Math.min(REBUILD_TIMEOUT_MS, options.deadlineMs - Date.now())),
    env: options.env,
    secrets: [],
  });
}

/** Copies one run's report and trace into `hidden/factory-trace/<name>/`, replacing an earlier copy. */
async function publishOne(options: TraceOptions, entry: TraceEntry): Promise<Published> {
  const target = join(options.hiddenDir, TRACE_DIR, entry.name);
  rmSync(target, { recursive: true, force: true });
  if (entry.runId === null) return { entry, files: [] };
  const source = join(options.repoRoot, 'runs', entry.runId);
  if (!existsSync(join(source, 'report.md')) && existsSync(join(source, 'trace.jsonl'))) await rebuildReport(options, entry.runId);
  const files = ['report.md', 'trace.jsonl'].filter((file) => existsSync(join(source, file)));
  if (files.length > 0) mkdirSync(target, { recursive: true });
  for (const file of files) cpSync(join(source, file), join(target, file));
  return { entry, files };
}

/** The line of one spec in REPORT.md. */
function runLine(index: number, published: Published): string {
  const { name, runId } = published.entry;
  if (runId === null) return `${String(index + 1)}. \`${name}\`: the factory printed no run id, so there is no report or trace.`;
  const links = published.files.map((file) => `[${file === 'report.md' ? 'report' : 'trace'}](${TRACE_DIR}/${name}/${file})`);
  const missing = ['report.md', 'trace.jsonl'].filter((file) => !published.files.includes(file));
  const tail = missing.length === 0 ? '' : `; missing: ${missing.join(', ')}`;
  return `${String(index + 1)}. \`${name}\`: run \`${runId}\`, ${links.length === 0 ? 'nothing to link' : links.join(', ')}${tail}.`;
}

/** The whole REPORT.md: when, the table and its failure details, then one line per run. */
export function renderReport(generatedAt: Date, table: string, details: readonly string[], published: readonly Published[]): string {
  return [
    '# Hidden run report',
    '',
    `Generated by the factory's hidden-run script at ${generatedAt.toISOString()}.`,
    '',
    '```',
    table,
    ...details,
    '```',
    '',
    '## Runs',
    '',
    'Each report gives the time, cost and models of every task and the human interventions; each trace is the full event log of the run.',
    '',
    ...published.map((one, index) => runLine(index, one)),
    '',
  ].join('\n');
}

/** Whether the reports and traces were published, and why not. */
export type PublishOutcome = { readonly ok: true } | { readonly ok: false; readonly reason: string };

/** Publishes every run's report and trace and writes `hidden/REPORT.md`; never throws. */
export async function publishTrace(
  options: TraceOptions,
  entries: readonly TraceEntry[],
  table: string,
  details: readonly string[],
  now: Date,
): Promise<PublishOutcome> {
  try {
    const published: Published[] = [];
    for (const entry of entries) published.push(await publishOne(options, entry));
    mkdirSync(options.hiddenDir, { recursive: true });
    writeFileSync(join(options.hiddenDir, 'REPORT.md'), renderReport(now, table, details, published));
    return { ok: true };
  } catch (error) {
    return { ok: false, reason: error instanceof Error ? error.message : String(error) };
  }
}
